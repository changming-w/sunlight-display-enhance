# Plot 6: Per-image multi-metric comparison (dot/lollipop plot)
# ---------------------------------------------------------------------------

def plot_per_image_lollipop(
    rows: List[Dict[str, str]],
    output_dir: Path
) -> None:
    """Lollipop plot showing gains per image for key metrics."""
    key_metrics = [
        ("rms_median_gain", "RMS Median Gain", 1.0),
        ("rms_p90_gain", "RMS P90 Gain", 1.0),
    ]

    names = []
    data = {k: [] for k, _, _ in key_metrics}

    for row in rows:
        name = row.get("key", row.get("original_image", ""))
        short_name = Path(name).stem[:18]
        has_any = False

        for metric_key, _, _ in key_metrics:
            v = safe_float(row.get(metric_key, ""))
            if v is not None:
                has_any = True

        if has_any:
            names.append(short_name)
            for metric_key, _, _ in key_metrics:
                v = safe_float(row.get(metric_key, ""))
                data[metric_key].append(v if v is not None else np.nan)

    if not names:
        return

    n = len(names)
    fig, ax = plt.subplots(figsize=(max(8, n * 0.6), 6))

    colors = ["#4C72B0", "#DD8452", "#55A868", "#C44E52"]
    x = np.arange(n)

    for i, (metric_key, label, ref) in enumerate(key_metrics):
        vals = np.array(data[metric_key])
        valid = ~np.isnan(vals)

        # Stem lines
        for j in range(n):
            if valid[j]:
                ax.plot([x[j] + i * 0.15, x[j] + i * 0.15],
                        [ref, vals[j]], color=colors[i % len(colors)],
                        linewidth=1.5, alpha=0.6)

        # Dots
        ax.scatter(x[valid] + i * 0.15, vals[valid],
                   color=colors[i % len(colors)], s=40, zorder=5, label=label)

    ax.axhline(y=1.0, color="gray", linestyle="--", alpha=0.5)
    ax.set_xticks(x + 0.075)
    ax.set_xticklabels(names, rotation=45, ha="right", fontsize=8)
    ax.set_ylabel("Gain (ratio)")
    ax.set_title("Per-Image RMS Contrast Gain")
    ax.legend(fontsize=9)
    ax.grid(axis="y", alpha=0.3)

    plt.tight_layout()
    out_path = output_dir / "per_image_gain_lollipop.png"
    plt.savefig(str(out_path), dpi=150)
    plt.close()
    print(f"  Saved: {out_path}")


# ---------------------------------------------------------------------------
# Plot 7: Local contrast heatmap (requires image files)
# ---------------------------------------------------------------------------

def compute_local_rms_map(img_path: Path, window: int = 15) -> Optional[np.ndarray]:
    """Compute local RMS contrast map for visualization."""
    try:
        data = np.fromfile(str(img_path), dtype=np.uint8)
        img = cv2.imdecode(data, cv2.IMREAD_UNCHANGED)
    except Exception:
        return None

    if img is None:
        return None

    # Convert to grayscale float
    if img.ndim == 3:
        if img.shape[2] == 4:
            img = img[:, :, :3]
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    else:
        gray = img

    y = gray.astype(np.float32) / 255.0

    k = window if window % 2 == 1 else window + 1

    mean = cv2.GaussianBlur(y, (k, k), 0, borderType=cv2.BORDER_REFLECT101)
    mean_sq = cv2.GaussianBlur(y * y, (k, k), 0, borderType=cv2.BORDER_REFLECT101)

    var = np.maximum(mean_sq - mean * mean, 0.0)
    std = np.sqrt(var)

    # Normalize to 0-255 for visualization
    contrast = std / (mean + 1e-4)
    contrast = np.clip(contrast, 0, np.percentile(contrast, 99))

    if contrast.max() > 0:
        contrast = (contrast / contrast.max() * 255).astype(np.uint8)
    else:
        contrast = np.zeros_like(gray)

    return contrast


def plot_heatmap_pair(
    orig_path: Path,
    enh_path: Path,
    output_dir: Path,
    window: int = 15
) -> None:
    """Generate side-by-side heatmap comparison for one image pair."""
    orig_map = compute_local_rms_map(orig_path, window)
    enh_map = compute_local_rms_map(enh_path, window)

    if orig_map is None or enh_map is None:
        return

    # Apply colormap
    orig_heat = cv2.applyColorMap(orig_map, cv2.COLORMAP_JET)
    enh_heat = cv2.applyColorMap(enh_map, cv2.COLORMAP_JET)

    # Match sizes
    h = min(orig_heat.shape[0], enh_heat.shape[0])
    w_orig = orig_heat.shape[1]
    w_enh = enh_heat.shape[1]

    if orig_heat.shape[0] != h:
        scale = h / orig_heat.shape[0]
        w_orig = int(orig_heat.shape[1] * scale)
        orig_heat = cv2.resize(orig_heat, (w_orig, h))

    if enh_heat.shape[0] != h:
        scale = h / enh_heat.shape[0]
        w_enh = int(enh_heat.shape[1] * scale)
        enh_heat = cv2.resize(enh_heat, (w_enh, h))

    # Separator
    sep = np.full((h, 4, 3), 255, dtype=np.uint8)

    # Labels bar
    total_w = w_orig + 4 + w_enh
    bar_h = 30
    bar = np.full((bar_h, total_w, 3), 255, dtype=np.uint8)

    font = cv2.FONT_HERSHEY_SIMPLEX
    cv2.putText(bar, "Original RMS Contrast", (10, 22), font, 0.6, (0, 0, 0), 1, cv2.LINE_AA)
    cv2.putText(bar, "Enhanced RMS Contrast", (w_orig + 14, 22), font, 0.6, (0, 0, 0), 1, cv2.LINE_AA)

    composite = np.vstack([bar, np.hstack([orig_heat, sep, enh_heat])])

    out_path = output_dir / f"{orig_path.stem}_contrast_heatmap.png"
    cv2.imencode(".png", composite)[1].tofile(str(out_path))
    print(f"  Saved heatmap: {out_path}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Visualize RMS/EME metrics from compute_rms_eme_pair.py output."
    )

    # Input mode 1: from CSV
    parser.add_argument("--csv", type=Path, default=None,
                        help="Path to paired_comparison_metrics.csv from compute_rms_eme_pair.py")

    # Input mode 2: from image folders (recompute)
    parser.add_argument("--original", type=Path, default=None,
                        help="Original image folder (for heatmap mode).")
    parser.add_argument("--enhanced", type=Path, default=None,
                        help="Enhanced image folder (for heatmap mode).")

    parser.add_argument("--output", "-o", type=Path, default=Path("./test/rms_eme_eval/plots"),
                        help="Output folder for plots.")

    # Heatmap options
    parser.add_argument("--heatmap", action="store_true",
                        help="Generate local contrast heatmap pairs.")
    parser.add_argument("--rms-window", type=int, default=15,
                        help="Window size for heatmap computation. Default: 15.")

    # Plot selection
    parser.add_argument("--no-bar", action="store_true",
                        help="Skip per-image bar charts.")
    parser.add_argument("--no-dist", action="store_true",
                        help="Skip distribution histograms.")
    parser.add_argument("--no-summary", action="store_true",
                        help="Skip summary overview plot.")
    parser.add_argument("--no-lollipop", action="store_true",
                        help="Skip per-image lollipop plot.")

    args = parser.parse_args()

    if not HAS_MATPLOTLIB:
        print("[Error] matplotlib is required. Install: pip install matplotlib")
        sys.exit(1)

    output_dir = args.output
    output_dir.mkdir(parents=True, exist_ok=True)

    # -----------------------------------------------------------------------
    # CSV-based visualization
    # -----------------------------------------------------------------------
    if args.csv is not None:
        if not args.csv.exists():
            print(f"[Error] CSV not found: {args.csv}")
            sys.exit(1)

        rows = read_csv_rows(args.csv)
        if not rows:
            print("[Error] CSV is empty.")
            sys.exit(1)

        print(f"Loaded {len(rows)} rows from {args.csv}")
        print(f"Output: {output_dir}")
        print("-" * 60)

        # Determine available EME modes from CSV columns
        has_classic = any("eme_classic" in k for k in rows[0].keys())
        has_percentile = any("eme_percentile" in k for k in rows[0].keys())

        if not args.no_bar:
            print("[1] Per-image RMS comparison...")
            plot_rms_comparison(rows, output_dir, metric_key="rms_median")
            plot_rms_comparison(rows, output_dir, metric_key="rms_mean")
            plot_rms_comparison(rows, output_dir, metric_key="rms_p90")

            print("[2] Per-image EME comparison...")
            if has_classic:
                plot_eme_comparison(rows, output_dir, mode="classic")
            if has_percentile:
                plot_eme_comparison(rows, output_dir, mode="percentile")

        if not args.no_dist:
            print("[3] RMS gain distribution...")
            plot_rms_gain_distribution(rows, output_dir, metric_key="rms_median_gain")
            plot_rms_gain_distribution(rows, output_dir, metric_key="rms_mean_gain")

            print("[4] EME delta distribution...")
            if has_classic:
                plot_eme_delta_distribution(rows, output_dir, mode="classic")
            if has_percentile:
                plot_eme_delta_distribution(rows, output_dir, mode="percentile")

        if not args.no_summary:
            print("[5] Summary overview...")
            plot_summary_overview(rows, output_dir)

        if not args.no_lollipop:
            print("[6] Per-image lollipop...")
            plot_per_image_lollipop(rows, output_dir)

    # -----------------------------------------------------------------------
    # Heatmap mode (requires image folders)
    # -----------------------------------------------------------------------
    if args.heatmap:
        if args.original is None or args.enhanced is None:
            print("[Error] --heatmap requires --original and --enhanced folders.")
            sys.exit(1)

        if not args.original.is_dir() or not args.enhanced.is_dir():
            print("[Error] --original and --enhanced must be directories.")
            sys.exit(1)

        print("\n[7] Generating contrast heatmaps...")
        heatmap_dir = output_dir / "heatmaps"
        heatmap_dir.mkdir(parents=True, exist_ok=True)

        IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"}

        orig_paths = sorted([
            p for p in args.original.glob("*")
            if p.is_file() and p.suffix.lower() in IMAGE_EXTS
        ])
        enh_dict = {
            p.name: p for p in args.enhanced.glob("*")
            if p.is_file() and p.suffix.lower() in IMAGE_EXTS
        }

        count = 0
        for orig_path in orig_paths:
            enh_path = enh_dict.get(orig_path.name)
            if enh_path is None:
                continue

            plot_heatmap_pair(orig_path, enh_path, heatmap_dir, args.rms_window)
            count += 1

        print(f"  Generated {count} heatmap pair(s) in {heatmap_dir}")

    # -----------------------------------------------------------------------
    # If neither CSV nor heatmap was requested
    # -----------------------------------------------------------------------
    if args.csv is None and not args.heatmap:
        print("[Error] Please provide --csv or use --heatmap with --original/--enhanced.")
        parser.print_help()
        sys.exit(1)

    print("\nDone!")


if __name__ == "__main__":
    main()
