def read_csv_rows(csv_path: Path) -> List[Dict[str, str]]:
    """Read CSV file into list of dicts."""
    rows = []
    with open(csv_path, "r", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append(dict(row))
    return rows


def safe_float(val: Any) -> Optional[float]:
    """Convert to float, return None if not possible."""
    if val is None or val == "":
        return None
    try:
        v = float(val)
        if not np.isfinite(v):
            return None
        return v
    except (ValueError, TypeError):
        return None


# ---------------------------------------------------------------------------
# Plot 1: Per-image RMS comparison bar chart
# ---------------------------------------------------------------------------

def plot_rms_comparison(
    rows: List[Dict[str, str]],
    output_dir: Path,
    metric_key: str = "rms_median",
    title_suffix: str = ""
) -> None:
    """Bar chart: original vs enhanced RMS metric per image."""
    names = []
    orig_vals = []
    enh_vals = []

    for row in rows:
        name = row.get("key", row.get("original_image", ""))
        orig = safe_float(row.get(f"orig_{metric_key}", ""))
        enh = safe_float(row.get(f"enh_{metric_key}", ""))

        if orig is not None and enh is not None:
            # Truncate long names
            short_name = Path(name).stem[:20]
            names.append(short_name)
            orig_vals.append(orig)
            enh_vals.append(enh)

    if not names:
        print(f"[Skip] No valid data for {metric_key}")
        return

    n = len(names)
    x = np.arange(n)
    width = 0.35

    fig, ax = plt.subplots(figsize=(max(8, n * 0.8), 5))
    bars1 = ax.bar(x - width / 2, orig_vals, width, label="Original", color="#4C72B0", alpha=0.85)
    bars2 = ax.bar(x + width / 2, enh_vals, width, label="Enhanced", color="#DD8452", alpha=0.85)

    ax.set_xlabel("Image")
    ax.set_ylabel(metric_key.replace("_", " ").title())
    ax.set_title(f"RMS Contrast: Original vs Enhanced ({metric_key}){title_suffix}")
    ax.set_xticks(x)
    ax.set_xticklabels(names, rotation=45, ha="right", fontsize=8)
    ax.legend()
    ax.grid(axis="y", alpha=0.3)

    plt.tight_layout()
    out_path = output_dir / f"rms_{metric_key}_comparison.png"
    plt.savefig(str(out_path), dpi=150)
    plt.close()
    print(f"  Saved: {out_path}")


# ---------------------------------------------------------------------------
# Plot 2: RMS gain distribution
# ---------------------------------------------------------------------------

def plot_rms_gain_distribution(
    rows: List[Dict[str, str]],
    output_dir: Path,
    metric_key: str = "rms_median_gain"
) -> None:
    """Histogram of RMS gain across images."""
    gains = []
    for row in rows:
        g = safe_float(row.get(metric_key, ""))
        if g is not None:
            gains.append(g)

    if not gains:
        print(f"[Skip] No valid gain data for {metric_key}")
        return

    gains = np.array(gains)

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.hist(gains, bins=min(20, max(5, len(gains) // 2)),
            color="#4C72B0", alpha=0.8, edgecolor="white")

    # Reference line at 1.0
    ax.axvline(x=1.0, color="red", linestyle="--", linewidth=1.5, label="No change (1.0x)")

    # Mean line
    mean_val = float(np.mean(gains))
    ax.axvline(x=mean_val, color="green", linestyle="-", linewidth=1.5,
               label=f"Mean ({mean_val:.3f}x)")

    ax.set_xlabel("Enhancement Gain (ratio)")
    ax.set_ylabel("Count")
    ax.set_title(f"Distribution of {metric_key.replace('_', ' ').title()}")
    ax.legend()
    ax.grid(axis="y", alpha=0.3)

    plt.tight_layout()
    out_path = output_dir / f"{metric_key}_distribution.png"
    plt.savefig(str(out_path), dpi=150)
    plt.close()
    print(f"  Saved: {out_path}")


