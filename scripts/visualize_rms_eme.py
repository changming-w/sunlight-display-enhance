"""
Visualize Local RMS Contrast and EME metrics from compute_rms_eme_pair.py output.

Reads the CSV files generated by compute_rms_eme_pair.py and produces:
1. Per-image bar chart: original vs enhanced RMS / EME side-by-side
2. Gain/delta distribution: histogram of enhancement factors across images
3. Summary radar/grouped bar: overview of all metric gains
4. (Optional) Local contrast heatmap for individual images

Usage
-----
    # From CSV files (default)
    python scripts/visualize_rms_eme.py \
        --csv ./test/rms_eme_eval/paired_comparison_metrics.csv \
        --output ./test/rms_eme_eval/plots

    # Directly from image folders (compute + visualize in one shot)
    python scripts/visualize_rms_eme.py \
        --original ./test/original \
        --enhanced ./test/enhanced \
        --output ./test/rms_eme_eval/plots \
        --rms-window 15 \
        --block-size 16

    # Generate local contrast heatmaps
    python scripts/visualize_rms_eme.py \
        --original ./test/original \
        --enhanced ./test/enhanced \
        --output ./test/rms_eme_eval/plots \
        --heatmap
"""

