# Plot 5: Summary grouped bar (all metrics overview)
# ---------------------------------------------------------------------------

def plot_summary_overview(
    rows: List[Dict[str, str]],
    output_dir: Path
) -> None:
    """Grouped bar summarizing mean gains/deltas across all metrics."""
    # Collect RMS gain metrics
    rms_gain_keys = ["rms_mean_gain", "rms_median_gain", "rms_p75_gain", "rms_p90_gain", "rms_p95_gain"]
    eme_delta_keys = ["eme_classic_delta_db", "eme_percentile_delta_db"]

    # --- RMS Gains subplot ---
    rms_labels = []
    rms_means = []
    rms_medians = []

    for key in rms_gain_keys:
        vals = []
        for row in rows:
            v = safe_float(row.get(key, ""))
            if v is not None:
                vals.append(v)
        if vals:
            rms_labels.append(key.replace("rms_", "").replace("_gain", ""))
            rms_means.append(float(np.mean(vals)))
            rms_medians.append(float(np.median(vals)))

    # --- EME Deltas subplot ---
    eme_labels = []
    eme_means = []
    eme_medians = []

    for key in eme_delta_keys:
        vals = []
        for row in rows:
            v = safe_float(row.get(key, ""))
            if v is not None:
                vals.append(v)
        if vals:
            label = key.replace("eme_", "").replace("_delta_db", "")
            eme_labels.append(label)
            eme_means.append(float(np.mean(vals)))
            eme_medians.append(float(np.median(vals)))

    has_rms = len(rms_labels) > 0
    has_eme = len(eme_labels) > 0

    if not has_rms and not has_eme:
        print("[Skip] No valid data for summary overview")
        return

    ncols = int(has_rms) + int(has_eme)
    fig, axes = plt.subplots(1, ncols, figsize=(6 * ncols, 5))
    if ncols == 1:
        axes = [axes]

    ax_idx = 0

    if has_rms:
        ax = axes[ax_idx]
        x = np.arange(len(rms_labels))
        width = 0.35
        ax.bar(x - width / 2, rms_means, width, label="Mean", color="#4C72B0", alpha=0.85)
        ax.bar(x + width / 2, rms_medians, width, label="Median", color="#DD8452", alpha=0.85)
        ax.axhline(y=1.0, color="red", linestyle="--", alpha=0.6, label="No change (1.0x)")
        ax.set_xticks(x)
        ax.set_xticklabels(rms_labels, fontsize=9)
        ax.set_ylabel("Gain (ratio)")
        ax.set_title("RMS Contrast Gain Summary")
        ax.legend(fontsize=8)
        ax.grid(axis="y", alpha=0.3)
        ax_idx += 1

    if has_eme:
        ax = axes[ax_idx]
        x = np.arange(len(eme_labels))
        width = 0.35
        ax.bar(x - width / 2, eme_means, width, label="Mean", color="#55A868", alpha=0.85)
        ax.bar(x + width / 2, eme_medians, width, label="Median", color="#C44E52", alpha=0.85)
        ax.axhline(y=0, color="red", linestyle="--", alpha=0.6, label="No change (0 dB)")
        ax.set_xticks(x)
        ax.set_xticklabels(eme_labels, fontsize=9)
        ax.set_ylabel("Delta (dB)")
        ax.set_title("EME Delta Summary")
        ax.legend(fontsize=8)
        ax.grid(axis="y", alpha=0.3)

    plt.tight_layout()
    out_path = output_dir / "summary_overview.png"
    plt.savefig(str(out_path), dpi=150)
    plt.close()
    print(f"  Saved: {out_path}")


